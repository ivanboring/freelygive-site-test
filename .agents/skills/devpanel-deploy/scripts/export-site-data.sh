#!/usr/bin/env bash
# Export the local DDEV site's database and public files for a manual import
# into a DevPanel application (references/import-on-devpanel.md).
#
# Writes .devpanel-export/{db.sql.gz,files.tgz,SHA256SUMS} in the project root
# and refuses to run unless that directory is git-ignored. Prints sizes and
# checksums only, never file contents.
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"
OUT=.devpanel-export
FILES_DIR=web/sites/default/files

if ! git check-ignore -q "$OUT/db.sql.gz"; then
  echo "Refusing: $OUT/ is not git-ignored (add /$OUT/ to .gitignore)." >&2
  exit 2
fi
DRUSH=vendor/bin/drush
[ -x "$DRUSH" ] || DRUSH=drush

mkdir -p "$OUT"
chmod 700 "$OUT"
rm -f "$OUT/db.sql.gz" "$OUT/files.tgz" "$OUT/SHA256SUMS"

# Cache, session, lock and log tables keep their structure but no rows.
# mariadb-dump (DDEV) starts with a "sandbox mode" line that MySQL clients
# reject ("Unknown command '\-'"), and DevPanel clusters run MySQL: drop it.
"$DRUSH" sql:dump --structure-tables-list='cache,cache_*,watchdog,sessions,semaphore,flood' \
  | sed '1{/enable the sandbox mode/d}' \
  | gzip -9 > "$OUT/db.sql.gz"

first="$(gunzip -c "$OUT/db.sql.gz" | head -n 1 || true)"
end="$(gunzip -c "$OUT/db.sql.gz" | tail -n 5)"
if [[ "$first" == *"sandbox mode"* ]]; then
  echo "Export failed: sandbox line still present." >&2
  exit 1
fi
if [[ "$end" != *"Dump completed"* ]]; then
  echo "Export failed: the dump did not complete." >&2
  exit 1
fi

# css/js/php/styles are regenerated by Drupal on the target.
tar -czf "$OUT/files.tgz" -C "$FILES_DIR" \
  --exclude=./css --exclude=./js --exclude=./php --exclude=./styles .

(cd "$OUT" && sha256sum db.sql.gz files.tgz > SHA256SUMS)

echo "Exported to $ROOT/$OUT (on the host: the project's .devpanel-export/ folder):"
ls -lh "$OUT" | awk 'NR > 1 { print "  " $5 "  " $9 }'
echo "Checksums:"
sed 's/^/  /' "$OUT/SHA256SUMS"
